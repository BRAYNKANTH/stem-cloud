                sp.reload();sp.locator('#pp-list button').first.wait_for()
                migrated=sp.evaluate("uid=>JSON.parse(localStorage.getItem('stem_pp_physics_'+uid))",legacy_id)
                check('legacy migration keeps physics draft only',migrated['drafts']['ol2015-ii-01']['answers']=={'iv':'saved physics'} and 'ol2015-i-01' not in migrated['drafts'])
                check('legacy mixed exam is cleared',migrated['exam'] is None)
                check('legacy data remains archived',sp.evaluate("uid=>localStorage.getItem('stem_pp_'+uid)!==null",legacy_id))
                second.close()

                page.locator('#pp-clear').click();page.locator('#pp-exam-i').click();page.locator('#pp-confirm [value=ok]').click()
                page.locator('#pp-exam-bar').wait_for()
                check('paper MCQ hides explanations',page.locator('.pp-feedback').count()==0)
                check('paper MCQ hides teaching and similar answers',page.locator('.pp-teaching,.pp-similar,.pp-references').count()==0)
                page.locator('[name=pp-choice][value="3"]').check()
                page.evaluate("()=>{const key='stem_pp_physics_'+SCX_USER.id;let s=JSON.parse(localStorage.getItem(key));s.exam.deadline=1;localStorage.setItem(key,JSON.stringify(s));}");page.reload();page.locator('#pp-exam-bar').wait_for()
                check('exam responses survive reload',page.locator('[name=pp-choice][value="3"]').is_checked())
