# -*- coding: utf-8 -*-
"""Lift the lesson pages' slider labs into modules for the new lesson pages: web/src/labs/slider/.

Nine lesson pages (hydrostatic pressure to electromagnetism) build their lab from the same template: a few sliders, a
two-part readout, a picture drawn by the page's CFG.draw with the drawing kit makeDraw, the guide (LAB: goal, tries,
what you see, live) and the cartoon stage with three missions (CFG: read, missions, draw). Only the data and the
functions differ, and the functions only read the sliders. So they are taken unchanged from each page:

    slider/draw.js            the drawing kit (makeDraw, the same in all nine pages), colours read from the picture
    slider/<lesson>.js        the lab: its controls, picture size and hint (META), and build(T, TT, APP_LANG, value)
                              returning the page's own CFG, LAB and stage CFG, with document.getElementById giving
                              the sliders' values; STRINGS, its English strings for the Sinhala looked up at build time
    slider/<Name>Lab.tsx      the island for it (labs/SliderLab.tsx with that lab)
    slider/index.ts           the labs by lesson, for labs/registry.ts
    slider/SliderLabs.astro   renders the right island (components/lesson/Step.astro)

    python tools/slider_labs.py           # write them
    python tools/slider_labs.py --check   # fail if they are not current (the lesson pages changed)
"""
import glob, html, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'web' / 'src' / 'labs' / 'slider'
MARK = 'INTERACTIVE LAB (sliders + live drawing)'
NOCHECK = "// @ts-nocheck (the lesson page's own code, unchanged; its types are in the .d.ts)\n"
HEAD = '// Generated by tools/slider_labs.py from %s. Do not edit: change the lesson page, then run the generator again.\n'


def scripts(s):
    return ''.join(re.findall(r'<script(?![^>]*src)[^>]*>(.*?)</script>', s, re.S))


def between(s, start, end, after=0):
    a = s.index(start, after)
    b = s.index(end, a + len(start))
    return s[a + len(start):b], b


def lessons_by_file():
    out = {}
    for f in glob.glob(str(ROOT / 'content' / '*' / '*' / '*' / 'lesson.json')):
        L = json.loads(Path(f).read_text(encoding='utf-8'))
        if L.get('legacy'):
            out[L['legacy']['file']] = L
    return out


def literals(js):
    """The English-looking string literals of some page code (for the Sinhala lookup)."""
    out = []
    for m in re.finditer(r'"((?:[^"\\\n]|\\.)*)"|\'((?:[^\'\\\n]|\\.)*)\'', js):
        if m.group(1) is not None:
            raw = m.group(1)
        else:   # a single-quoted literal, as a double-quoted one
            raw = re.sub(r'(?<!\\)"', '\\"', m.group(2).replace("\\'", "'"))
        try:
            v = json.loads('"' + raw + '"')
        except ValueError:
            v = raw
        if re.search(r'[A-Za-z]{2}', v) and not re.search(r'[஀-௿]', v):
            out.append(v)
    return out


def lab(path, lesson):
    s = Path(path).read_text(encoding='utf-8')
    sc = scripts(s)
    # the markup: controls, the picture, the hint
    a = s.index('<section class="block" id="lab">')
    sec = s[a:s.index('</section>', a)]
    controls = []
    for m in re.finditer(r'<div class="control">\s*<label for="(\w+)Slider"><span data-ta="([^"]*)">([^<]*)</span>(.*?)<b id="\w+Val">[^<]*</b>(.*?)</label>\s*'
                         r'<input type="range" id="\w+Slider" min="([^"]+)" max="([^"]+)" step="([^"]+)" value="([^"]+)">', sec, re.S):
        cid, ta, en, mid, unit, lo, hi, step, val = m.groups()
        controls.append({'id': cid, 'name': [html.unescape(en.strip()), html.unescape(ta)], 'mid': mid, 'unit': unit.strip(),
                         'min': float(lo), 'max': float(hi), 'step': float(step), 'value': float(val)})
    if not controls:
        sys.exit('%s: no sliders found; update tools/slider_labs.py' % path)
    view = re.search(r'<svg id="labSvg" viewBox="([^"]+)"', sec).group(1)
    hm = re.search(r'<p class="lab-hint" data-ta="([^"]*)">(.*?)</p>', sec, re.S)
    hint = [hm.group(2).strip(), hm.group(1)]
    # the code: the lab's CFG, the guide's LAB, the stage's CFG and its device key
    i = sc.index(MARK)
    cfg, _ = between(sc, 'const CFG = ', ";\n  const svg = document.getElementById('labSvg');", i)
    g = sc.index('GUIDED LAB')
    guide, _ = between(sc, 'const LAB = ', '\n};', g)
    st = sc.index('CARTOON LAB STAGE')
    stage, e = between(sc, 'const CFG = ', '\n};', st)
    key = re.search(r"const LID2 = '([^']+)';", sc[e:e + 200]).group(1)
    ids = sorted(set(re.findall(r"'(\w+)Slider'", guide + stage)))
    if not set(ids) <= {c['id'] for c in controls}:
        sys.exit('%s: the guide or stage reads %s; update tools/slider_labs.py' % (path, ids))
    meta = {'lesson': lesson['id'], 'legacy': key, 'controls': controls, 'viewBox': view, 'hint': hint}
    # the stage shows each mission as "Mission <n>: ..." (labs/shared.tsx), the guide's picture line as "In the picture: ..."
    missions = ['Mission %d: %s' % (n + 1, json.loads('"%s"' % m)) for n, m in enumerate(re.findall(r'\{en:"((?:[^"\\]|\\.)*)"', stage))]
    look = re.search(r'look:\s*\["((?:[^"\\]|\\.)*)"', guide)
    strings = ([c['name'][0] for c in controls] + [hint[0]] + missions + (['In the picture: ' + json.loads('"%s"' % look.group(1))] if look else [])
               + literals(cfg + guide + stage))
    return meta, cfg.rstrip(), guide.rstrip() + '\n}', stage.rstrip() + '\n}', strings


def draw_kit(paths):
    kits = set()
    for p in paths:
        sc = scripts(Path(p).read_text(encoding='utf-8'))
        body, _ = between(sc, 'function makeDraw(svg){', '\n  return D;\n}')
        kits.add(body)
    if len(kits) != 1:
        sys.exit('the slider labs have %d different drawing kits; port the differences first' % len(kits))
    body = kits.pop()
    old_c, old_t = 'const C = cssVar;', 't.textContent = (window.STEM_LANG === \'si\' && window.StemSI) ? window.StemSI.t(String(str)) : str;'
    if body.count(old_c) != 1 or body.count(old_t) != 1:
        sys.exit('the drawing kit changed; update tools/slider_labs.py')
    body = body.replace(old_c, 'const C = (name) => getComputedStyle(svg).getPropertyValue(name).trim();')
    body = body.replace(old_t, 't.textContent = (si && si(String(str))) || str;')
    return ('// Generated by tools/slider_labs.py from the lesson pages\' drawing kit (makeDraw, the same in the %d slider-lab pages).\n'
            '// Do not edit. Colours are read from the picture; si(en) gives the Sinhala for the text it draws.\n'
            '/* eslint-disable */\n' + NOCHECK +
            'const SVGNS = \'http://www.w3.org/2000/svg\';\n'
            'function el(tag, attrs) {\n  const e = document.createElementNS(SVGNS, tag);\n  for (const k in attrs) { e.setAttribute(k, attrs[k]); }\n  return e;\n}\n'
            'export function makeDraw(svg, si) {%s\n  return D;\n}\n') % (len(paths), body)


def camel(slug):
    return ''.join(w.capitalize() for w in slug.split('-'))


def render():
    paths = [p for p in sorted(glob.glob(str(ROOT / 'site' / 'lessons' / '*.html'))) if MARK in Path(p).read_text(encoding='utf-8')]
    by_file = lessons_by_file()
    files = {'draw.js': draw_kit(paths),
             'draw.d.ts': '// Generated by tools/slider_labs.py. The lesson pages\' drawing kit (D.line, D.rect, D.text, D.arrow, ...).\n'
                          'export function makeDraw(svg: SVGSVGElement, si?: ((en: string) => string | null) | null): any;\n'}
    index, astro_imports, astro_uses = [], [], []
    for p in paths:
        name = Path(p).name
        lesson = by_file.get(name)
        if not lesson:
            sys.exit('%s has no lesson in content/' % name)
        slug = lesson['slug'] if 'slug' in lesson else lesson['id'].split('.')[-1]
        meta, cfg, guide, stage, strings = lab(p, lesson)
        strings = list(dict.fromkeys(strings))
        files[slug + '.js'] = (HEAD % ('site/lessons/' + name) + '/* eslint-disable */\n' + NOCHECK +
            'export const META = %s;\n\n'
            '/** Its English strings, for the Sinhala looked up at build time. */\n'
            'export const STRINGS = %s;\n\n'
            '/** The page\'s own lab (CFG), guide (LAB) and stage (STAGE); document.getElementById(id).value is a slider\'s value. */\n'
            'export function build(T, TT, APP_LANG, value) {\n'
            '  const document = { getElementById: (id) => ({ value: String(value(id.replace(/Slider$/, \'\'))) }) };\n'
            '  const CFG = %s;\n'
            '  const LAB = %s;\n'
            '  const STAGE = %s;\n'
            '  return { CFG, LAB, STAGE };\n'
            '}\n') % (json.dumps(meta, ensure_ascii=False, indent=1), json.dumps(strings, ensure_ascii=False, indent=1), cfg, guide, stage)
        files[slug + '.d.ts'] = (HEAD % ('site/lessons/' + name) +
            "import type { SliderLabModule } from '../SliderLab';\n"
            'export const META: SliderLabModule[\'META\'];\nexport const STRINGS: string[];\nexport const build: SliderLabModule[\'build\'];\n')
        comp = camel(slug) + 'Lab'
        files[comp + '.tsx'] = (HEAD % ('site/lessons/' + name) +
            "import type { SiDict } from '../../lib/si-lookup';\n"
            "import SliderLab from '../SliderLab';\n"
            "import * as lab from './%s.js';\n\n"
            'export default function %s(props: { si?: SiDict; legacy?: string }) {\n'
            '  return <SliderLab lab={lab} {...props} />;\n'
            '}\n') % (slug, comp)
        index.append((lesson['id'], slug))
        astro_imports.append("import %s from './%s';" % (comp, comp))
        astro_uses.append("{island === '%s' && <%s client:visible si={si} legacy={legacy} />}" % (slug, comp))
    files['index.ts'] = ('// Generated by tools/slider_labs.py: the slider labs by lesson (labs/registry.ts).\n'
        + ''.join("import { STRINGS as S%d } from './%s.js';\n" % (i, s) for i, (_, s) in enumerate(index))
        + '\nexport const SLIDER_LABS: Record<string, { island: string; strings: string[] }> = {\n'
        + ''.join("  '%s/lab': { island: '%s', strings: S%d },\n" % (lid, s, i) for i, (lid, s) in enumerate(index))
        + '};\n')
    files['SliderLabs.astro'] = ('---\n// Generated by tools/slider_labs.py: the island of a slider lab (components/lesson/Step.astro).\n'
        "import type { SiDict } from '../../lib/si-lookup';\n" + '\n'.join(astro_imports) +
        '\ninterface Props { island: string; si: SiDict; legacy?: string }\nconst { island, si, legacy } = Astro.props;\n---\n'
        + '\n'.join(astro_uses) + '\n')
    return files


if __name__ == '__main__':
    files = render()
    if '--check' in sys.argv:
        stale = [n for n, t in files.items() if not (OUT / n).is_file() or (OUT / n).read_text(encoding='utf-8').replace('\r\n', '\n') != t]
        extra = [p.name for p in OUT.glob('*') if p.name not in files] if OUT.is_dir() else []
        if stale or extra:
            sys.exit('web/src/labs/slider/ is not current (%s): run python tools/slider_labs.py' % ', '.join(stale + extra))
        print('the slider labs are current (%d files)' % len(files))
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for n, t in files.items():
            (OUT / n).write_text(t, encoding='utf-8', newline='\n')
        print('wrote %d files in %s' % (len(files), OUT.relative_to(ROOT).as_posix()))
