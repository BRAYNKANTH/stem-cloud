# -*- coding: utf-8 -*-
"""Lift the lesson pages' challenge mini-games into modules for the new lesson pages: web/src/games/challenge/.

The nine slider-lab pages (tools/slider_labs.py) also share their game: a few levels, each a question with a picture;
the student sets a slider to the answer and checks it, and gets up to three stars by how close it is. Only the game's
G (the levels, the picture function scene(D, level, state, guess, TT), the win and lose messages, the slider's range)
and its device key differ, so they are taken unchanged from each page:

    challenge/<lesson>.js          META (the stars key, the badge, the hint) and build(TT) returning the page's own G;
                                   STRINGS, its English strings for the Sinhala looked up at build time
    challenge/<Name>Game.tsx       the island for it (games/ChallengeGame.tsx with that game)
    challenge/index.ts             the games by lesson
    challenge/ChallengeGames.astro renders the right island (components/lesson/Step.astro)

The picture uses the slider labs' drawing kit (labs/slider/draw.js).

    python tools/challenge_games.py           # write them
    python tools/challenge_games.py --check   # fail if they are not current (the lesson pages changed)
"""
import glob, html, json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from slider_labs import NOCHECK, between, camel, literals, scripts  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'web' / 'src' / 'games' / 'challenge'
MARK = '\n   CHALLENGE MINI-GAME\n'
HEAD = '// Generated by tools/challenge_games.py from %s. Do not edit: change the lesson page, then run the generator again.\n'


def game(path, lesson):
    s = Path(path).read_text(encoding='utf-8')
    sc = scripts(s)
    a = s.index('<section class="block" id="challenge">')
    sec = s[a:s.index('</section>', a)]
    i = sc.index(MARK)
    G, _ = between(sc, 'const G = ', ";\n  const STARS_KEY = '", i)
    key = re.search(r"const STARS_KEY = '([^']+)';", sc[i:]).group(1)
    pfx = re.search(r"const PFX = '([^']*)';", sc)
    champ = re.search(r"function pushItLevelResult\(stars, allLevelsCleared\)\{\s*if\(stars>0\) addXP\(stars\*10, [^;]*;\s*if\(allLevelsCleared\) awardBadge\((PFX\s*\+\s*)?'([^']+)'\);", sc)
    if not champ or (champ.group(1) and not pfx):
        sys.exit('%s: pushItLevelResult changed; update tools/challenge_games.py' % path)
    badge = (pfx.group(1) if champ.group(1) else '') + champ.group(2)
    view = re.search(r'<svg id="gameSvg" viewBox="([^"]+)"', sec).group(1)
    hm = re.search(r'<p class="lab-hint" data-ta="([^"]*)">(.*?)</p>', sec, re.S)
    guess = re.search(r'<span data-ta="([^"]*)">([^<]*)</span> = <b id="gameGuessVal">', sec)
    check = re.search(r'<button class="btn primary" id="gameCheckBtn" data-ta="([^"]*)">([^<]*)</button>', sec)
    if not (hm and guess and check):
        sys.exit('%s: the challenge markup changed; update tools/challenge_games.py' % path)
    meta = {'lesson': lesson['id'], 'starsKey': key, 'badge': badge, 'viewBox': view,
            'hint': [hm.group(2).strip(), hm.group(1)], 'guess': [guess.group(2), html.unescape(guess.group(1))],
            'check': [check.group(2), html.unescape(check.group(1))]}
    strings = [meta['hint'][0], meta['guess'][0], meta['check'][0]] + literals(G)
    return meta, G.rstrip(), strings


def render():
    lessons = {}
    for f in glob.glob(str(ROOT / 'content' / '*' / '*' / '*' / 'lesson.json')):
        L = json.loads(Path(f).read_text(encoding='utf-8'))
        if L.get('legacy'):
            lessons[L['legacy']['file']] = L
    paths = [p for p in sorted(glob.glob(str(ROOT / 'site' / 'lessons' / '*.html'))) if MARK in scripts(Path(p).read_text(encoding='utf-8'))]
    files, index, imports, uses = {}, [], [], []
    for p in paths:
        name = Path(p).name
        L = lessons[name]
        slug = L['slug']
        meta, G, strings = game(p, L)
        src = HEAD % ('site/lessons/' + name)
        files[slug + '.js'] = (src + '/* eslint-disable */\n' + NOCHECK +
            'export const META = %s;\n\n'
            '/** Its English strings, for the Sinhala looked up at build time. */\n'
            'export const STRINGS = %s;\n\n'
            '/** The page\'s own game G: levels, scene(D, level, state, guess, TT), win, lose and the slider\'s range. */\n'
            'export function build(TT) {\n'
            '  return %s;\n'
            '}\n') % (json.dumps(meta, ensure_ascii=False, indent=1), json.dumps(list(dict.fromkeys(strings)), ensure_ascii=False, indent=1), G)
        files[slug + '.d.ts'] = (src + "import type { ChallengeModule } from '../ChallengeGame';\n"
            "export const META: ChallengeModule['META'];\nexport const STRINGS: string[];\nexport const build: ChallengeModule['build'];\n")
        comp = camel(slug) + 'Game'
        files[comp + '.tsx'] = (src + "import type { SiDict } from '../../lib/si-lookup';\n"
            "import ChallengeGame from '../ChallengeGame';\n"
            "import * as game from './%s.js';\n\n"
            'export default function %s(props: { si?: SiDict; stepId?: string }) {\n'
            '  return <ChallengeGame game={game} {...props} />;\n'
            '}\n') % (slug, comp)
        index.append((L['id'], slug))
        imports.append("import %s from './%s';" % (comp, comp))
        uses.append("{island === '%s' && <%s client:visible si={si} stepId={stepId} />}" % (slug, comp))
    files['index.ts'] = ('// Generated by tools/challenge_games.py: the challenge games by lesson.\n'
        + ''.join("import { STRINGS as S%d } from './%s.js';\n" % (i, s) for i, (_, s) in enumerate(index))
        + '\nexport const CHALLENGES: Record<string, { island: string; strings: string[] }> = {\n'
        + ''.join("  '%s': { island: '%s', strings: S%d },\n" % (lid, s, i) for i, (lid, s) in enumerate(index)) + '};\n')
    files['ChallengeGames.astro'] = ('---\n// Generated by tools/challenge_games.py: the island of a challenge game (components/lesson/Step.astro).\n'
        "import type { SiDict } from '../../lib/si-lookup';\n" + '\n'.join(imports) +
        '\ninterface Props { island: string; si: SiDict; stepId: string }\nconst { island, si, stepId } = Astro.props;\n---\n'
        + '\n'.join(uses) + '\n')
    return files


if __name__ == '__main__':
    files = render()
    if '--check' in sys.argv:
        stale = [n for n, t in files.items() if not (OUT / n).is_file() or (OUT / n).read_text(encoding='utf-8').replace('\r\n', '\n') != t]
        extra = [p.name for p in OUT.glob('*') if p.name not in files] if OUT.is_dir() else []
        if stale or extra:
            sys.exit('web/src/games/challenge/ is not current (%s): run python tools/challenge_games.py' % ', '.join(stale + extra))
        print('the challenge games are current (%d files)' % len(files))
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for n, t in files.items():
            (OUT / n).write_text(t, encoding='utf-8', newline='\n')
        print('wrote %d files in %s' % (len(files), OUT.relative_to(ROOT).as_posix()))
