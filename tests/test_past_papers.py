                page.locator('#pp-ta').click()
                check('Tamil source appears first with its own page',page.locator('.pp-book-ref').first.get_attribute('href')=='/lessons/textbooks/g10-p2-ta.pdf#page=94' and '84' in page.locator('.pp-book-ref').first.inner_text())
                page.locator('#pp-en').click()
                pdf=ctx.request.get(BASE+'/lessons/textbooks/g10-p2-en.pdf',headers={'Range':'bytes=0-1023'})
                check('textbook PDF served with byte ranges',pdf.status==206 and pdf.headers.get('content-type')=='application/pdf' and pdf.body().startswith(b'%PDF'))
                page.locator('#pp-list [data-q="ol2015-i-05"]').click()
                page.locator('#pp-bookmark').click();page.wait_for_timeout(250)
                page.locator('#pp-review').select_option('saved')
                check('bookmark filter',page.locator('#pp-list button').count()==1)
                page.locator('#pp-clear').click();page.locator('#pp-type').select_option('written')
                page.locator('#pp-answer-0').fill('Transverse waves; particles oscillate perpendicular to travel.')
                page.locator('.pp-solution > summary').first.click()
                check('written model answer includes teaching notes',page.locator('.pp-solution .pp-teaching').first.is_visible())
                page.locator('#pp-save-written').click();page.wait_for_timeout(250)
                page.locator('#pp-ta').click()
