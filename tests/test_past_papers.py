                check('worked calculations visible',page.locator('.pp-feedback').inner_text().find('36 g')>=0 and 'Worked steps' in page.locator('.pp-feedback').inner_text())
                check('verified grade and chapter link',page.locator('.pp-references a').first.get_attribute('href')=='/lessons/g10-chapter-15-hydrostatic-pressure.html' and 'Grade 10 · Chapter 15' in page.locator('.pp-references a').first.inner_text())
