# -*- coding: utf-8 -*-
"""Port the past papers page's styles to the new page: web/src/styles/past-papers.css.

The current page has its own stylesheet (public/static/past-papers.css, a dark look) that the bright theme overrides
(the .pp- rules in public/static/theme-bright.css). This writes both, in that order, after a block that maps the
variables they use to the design tokens, so the new page follows light and dark like every other new page.

    python tools/past_papers_css.py           # write it
    python tools/past_papers_css.py --check   # fail if it is not current
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'web' / 'src' / 'styles' / 'past-papers.css'
OWN = ROOT / 'public' / 'static' / 'past-papers.css'
BRIGHT = ROOT / 'public' / 'static' / 'theme-bright.css'

HEAD = '''/* Generated by tools/past_papers_css.py from public/static/past-papers.css and the .pp- rules of
   public/static/theme-bright.css. Do not edit: change those, then run the generator again.
   The variables they use are mapped to the design tokens here. */
.pp-page {
  --bg: var(--sc-ground); --panel: var(--sc-panel); --panel-2: var(--sc-panel-2); --border: var(--sc-line);
  --text: var(--sc-ink); --text-dim: var(--sc-ink-2); --accent: var(--sc-blue);
}
'''


def bright_rules() -> str:
    css = re.sub(r'/\*.*?\*/', '', BRIGHT.read_text(encoding='utf-8'), flags=re.S)
    out = []
    for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', css):
        sel = m.group(1).strip()
        if '@' in sel:
            continue
        if 'pp-' in sel and not re.search(r'data-theme', sel):
            sel = re.sub(r'(?:html\s+)?body\.pp-page', '.pp-page', sel)      # the new page puts .pp-page on a wrapper, not on <body>
            out.append('%s{%s}' % (sel, m.group(2).strip()))
    return '\n'.join(out)


def render() -> str:
    own = OWN.read_text(encoding='utf-8').strip()
    # the page's own font stack: the new pages set type from the design tokens
    own = re.sub(r'font:16px/1\.65 system-ui,"Noto Sans Tamil",sans-serif;', 'font-size:16px;line-height:1.65;', own)
    return HEAD + own + '\n/* the bright theme */\n' + bright_rules() + '\n'


if __name__ == '__main__':
    css = render()
    if '--check' in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding='utf-8').replace('\r\n', '\n') != css:
            sys.exit('web/src/styles/past-papers.css is not current: run python tools/past_papers_css.py')
        print('past-papers.css is current')
    else:
        OUT.write_text(css, encoding='utf-8', newline='\n')
        print('wrote %s (%.1f KB)' % (OUT.relative_to(ROOT).as_posix(), len(css.encode()) / 1024))
