# -*- coding: utf-8 -*-
"""Generate the lesson format's JSON Schema and TypeScript types from content_schema/lesson.py.

    python tools/content_types.py          # writes content_schema/lesson.schema.json and web/src/lib/content-types.ts
    python tools/content_types.py --check  # CI: fails if either file is out of date

The TypeScript types come from the JSON Schema through json-schema-to-typescript (web/node_modules, `npm ci` in web/).
"""
import json, os, shutil, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from content_schema import Lesson  # noqa: E402

SCHEMA_OUT = ROOT / 'content_schema' / 'lesson.schema.json'
TS_OUT = ROOT / 'web' / 'src' / 'lib' / 'content-types.ts'
TS_HEADER = '// Generated by tools/content_types.py from content_schema/lesson.py. Do not edit; regenerate instead.\n\n'


def schema_text() -> str:
    schema = Lesson.model_json_schema(by_alias=True)
    schema['$id'] = 'https://www.stemcloud.site/schemas/lesson-2.json'
    schema['title'] = 'Lesson'
    return json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + '\n'


def ts_text(schema: str) -> str:
    bin_dir = ROOT / 'web' / 'node_modules' / '.bin'
    json2ts = shutil.which('json2ts', path=str(bin_dir))
    if not json2ts:
        sys.exit('json2ts not found: run `npm ci` in web/ first')
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / 'lesson.schema.json'
        src.write_text(schema, encoding='utf-8')
        out = subprocess.run([json2ts, '--input', str(src), '--bannerComment', '', '--unreachableDefinitions', '--style.singleQuote'],
                             capture_output=True, text=True, encoding='utf-8', cwd=str(ROOT / 'web'), shell=os.name == 'nt')
    if out.returncode:
        sys.exit('json2ts failed:\n' + out.stderr)
    return TS_HEADER + out.stdout.replace('\r\n', '\n').strip() + '\n'


def main():
    check = '--check' in sys.argv
    schema = schema_text()
    ts = ts_text(schema)
    stale = []
    for path, text in ((SCHEMA_OUT, schema), (TS_OUT, ts)):
        old = path.read_text(encoding='utf-8').replace('\r\n', '\n') if path.exists() else None
        if old != text:
            if check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(text, encoding='utf-8', newline='\n')
                print('wrote', path.relative_to(ROOT))
    if stale:
        sys.exit('out of date (run python tools/content_types.py): ' + ', '.join(stale))
    if check:
        print('lesson schema and TypeScript types are up to date')


if __name__ == '__main__':
    main()
