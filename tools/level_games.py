# -*- coding: utf-8 -*-
"""Lift the lesson pages' one-off level games into modules for the new lesson pages: web/src/games/levels/.

Six pages have a game of their own (motion's and Newton's hold games, push-it, tug of war, the balance game,
equilibrium's hold game). Each is the same kind of thing: levels, a picture, a slider for your answer, a button, up
to three stars per level kept on the device, and SCX.pushItLevelResult(stars, all) for the XP and the badge. But
each is written its own way, so rather than port them one by one, each page's own markup (the game card) and its own
script (the game's IIFE) are taken unchanged, and games/LevelGame.tsx runs the script on the markup inside the
island: document.getElementById looks inside the game, and the page's helpers (el, cssVar, safeGet, safeSet, SCX,
APP_LANG) are given to it. Its language hook (<x>LangHook) is kept so a change of language redraws it.

    levels/<lesson>.js          HTML (the game card), META (stars key, badge, step) and run(root, env)
    levels/<Name>Game.tsx       the island for it
    levels/index.ts             the games by lesson
    levels/LevelGames.astro     renders the right island (components/lesson/Step.astro)

    python tools/level_games.py           # write them
    python tools/level_games.py --check   # fail if they are not current (the lesson pages changed)
"""
import glob, json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from slider_labs import NOCHECK, camel, literals, scripts  # noqa: E402
from sort_games import literal  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'web' / 'src' / 'games' / 'levels'
GAMES = {'holdgame', 'pushit', 'tugofwar', 'balancegame'}       # the game steps written their own way
HEAD = '// Generated by tools/level_games.py from %s. Do not edit: change the lesson page, then run the generator again.\n'


def card(sec):
    """The game card: the <div class="lab-card"> of the section, whole."""
    a = sec.index('<div class="lab-card">')
    depth, i = 0, a
    for m in re.finditer(r'<div\b|</div>', sec[a:]):
        depth += 1 if m.group(0) == '<div' else -1
        if depth == 0:
            return sec[a:a + m.end()]
    raise ValueError('unclosed lab-card')


def game(path, step):
    s = Path(path).read_text(encoding='utf-8')
    sc = scripts(s)
    a = s.index('<section class="block" id="%s">' % step)
    sec = s[a:s.index('</section>', a)]
    html = card(sec)
    ids = re.findall(r'id="([A-Za-z0-9_]+)"', html)
    # the script: the IIFE that looks up the game's first element
    first = next(i for i in ids if 'LevelRow' in i or i == 'levelRow')
    k = sc.index("document.getElementById('%s')" % first)
    start = sc.rindex('(function(){', 0, k)
    body = literal(sc, sc.index('{', start))          # the function body, braces included
    key = re.search(r"(?:STAR_KEY = |safeGet\()'(scx_[a-z0-9_]+_stars)'", body).group(1)
    hook = re.search(r'\b(\w+LangHook) = ', body)
    pfx = re.search(r"const PFX = '([^']*)';", sc)
    champ = re.search(r"function pushItLevelResult\(stars, allLevelsCleared\)\{\s*if\(stars>0\) addXP\(stars\*10, [^;]*;\s*if\(allLevelsCleared\) awardBadge\((PFX\s*\+\s*)?'([^']+)'\);", sc)
    if not champ:
        sys.exit('%s: pushItLevelResult changed; update tools/level_games.py' % path)
    badge = (pfx.group(1) if champ.group(1) else '') + champ.group(2)
    for name in re.findall(r'\b(SCX\.\w+)', body):
        if name not in ('SCX.pushItLevelResult', 'SCX.sndWrong', 'SCX.sndCorrect'):
            sys.exit('%s: the game uses %s; give it to the game in games/LevelGame.tsx' % (path, name))
    texts = [re.sub(r'<[^>]+>', '', t).strip() for t in re.findall(r'>([^<>]*[A-Za-z]{2}[^<>]*)<', html)]
    meta = {'starsKey': key, 'badge': badge, 'hook': hook.group(1) if hook else None}
    return html, meta, body, [t for t in texts if t] + literals(body)


def render():
    files, index, imports, uses = {}, [], [], []
    for f in sorted(glob.glob(str(ROOT / 'content' / '*' / '*' / '*' / 'lesson.json'))):
        L = json.loads(Path(f).read_text(encoding='utf-8'))
        steps = [st['id'] for st in L['steps'] if st['type'] == 'game' and st['id'] in GAMES]
        if not steps or not L.get('legacy'):
            continue
        step = steps[0]
        name = L['legacy']['file']
        html, meta, body, strings = game(ROOT / 'site' / 'lessons' / name, step)
        meta['lesson'], meta['step'] = L['id'], step
        slug = L['slug']
        hook = meta['hook']
        src = HEAD % ('site/lessons/' + name)
        files[slug + '.js'] = (src + '/* eslint-disable */\n' + NOCHECK +
            'export const HTML = %s;\n\n'
            'export const META = %s;\n\n'
            '/** Its English strings, for the Sinhala looked up at build time. */\n'
            'export const STRINGS = %s;\n\n'
            '/** The page\'s own game script, run on HTML inside root; env gives it the page\'s helpers. */\n'
            'export function run(root, env) {\n'
            '  const document = { getElementById: (id) => root.querySelector(\'#\' + id), createElement: (t) => globalThis.document.createElement(t) };\n'
            '  const { APP_LANG, el, cssVar, safeGet, safeSet, SCX } = env;\n'
            '  %s\n'
            '  (function()%s)();\n'
            '  return { lang: %s };\n'
            '}\n') % (json.dumps(html, ensure_ascii=False), json.dumps(meta, ensure_ascii=False, indent=1),
                      json.dumps(list(dict.fromkeys(strings)), ensure_ascii=False, indent=1),
                      ('let %s = null;' % hook) if hook else '', body, ('() => %s && %s()' % (hook, hook)) if hook else 'null')
        files[slug + '.d.ts'] = (src + "import type { LevelGameModule } from '../LevelGame';\n"
            "export const HTML: string;\nexport const META: LevelGameModule['META'];\nexport const STRINGS: string[];\nexport const run: LevelGameModule['run'];\n")
        comp = camel(slug) + 'Game'
        files[comp + '.tsx'] = (src + "import type { SiDict } from '../../lib/si-lookup';\n"
            "import LevelGame from '../LevelGame';\n"
            "import * as game from './%s.js';\n\n"
            'export default function %s(props: { si?: SiDict }) {\n'
            '  return <LevelGame game={game} {...props} />;\n'
            '}\n') % (slug, comp)
        index.append((L['id'], slug))
        imports.append("import %s from './%s';" % (comp, comp))
        uses.append("{island === '%s' && <%s client:visible si={si} />}" % (slug, comp))
    files['index.ts'] = ('// Generated by tools/level_games.py: the one-off level games by lesson.\n'
        + ''.join("import { STRINGS as S%d } from './%s.js';\n" % (i, s) for i, (_, s) in enumerate(index))
        + '\nexport const LEVEL_GAMES: Record<string, { island: string; strings: string[] }> = {\n'
        + ''.join("  '%s': { island: '%s', strings: S%d },\n" % (lid, s, i) for i, (lid, s) in enumerate(index)) + '};\n')
    files['LevelGames.astro'] = ('---\n// Generated by tools/level_games.py: the island of a level game (components/lesson/Step.astro).\n'
        "import type { SiDict } from '../../lib/si-lookup';\n" + '\n'.join(imports) +
        '\ninterface Props { island: string; si: SiDict }\nconst { island, si } = Astro.props;\n---\n' + '\n'.join(uses) + '\n')
    return files


if __name__ == '__main__':
    files = render()
    if '--check' in sys.argv:
        stale = [n for n, t in files.items() if not (OUT / n).is_file() or (OUT / n).read_text(encoding='utf-8').replace('\r\n', '\n') != t]
        extra = [p.name for p in OUT.glob('*') if p.name not in files] if OUT.is_dir() else []
        if stale or extra:
            sys.exit('web/src/games/levels/ is not current (%s): run python tools/level_games.py' % ', '.join(stale + extra))
        print('the level games are current (%d files)' % len(files))
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for n, t in files.items():
            (OUT / n).write_text(t, encoding='utf-8', newline='\n')
        print('wrote %d files in %s' % (len(files), OUT.relative_to(ROOT).as_posix()))
