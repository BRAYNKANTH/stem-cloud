# -*- coding: utf-8 -*-
"""Lift the lesson pages' Watch animations into modules for the new lesson pages: web/src/watch/.

Every lesson page's Watch step is a cartoon (Raja and Chittu) with captions, questions to predict, sound and a time
slider: its card markup (div.lab-card.fw-anim, with the takeaways) and its own player script (the animation's CFG
and the player around it), drawn with the cartoon engine that is already lifted (labs/engine.js, tools/lab_engine.py).
Both are taken unchanged from each page, and watch/WatchAnim.tsx runs the script on the markup inside the island,
with what it used from its page (window.__fwMakeH, T's Sinhala, SCX, __fwMark).

    watch/<lesson>.card.js     HTML: the card (on the built page, and to start again from)
    watch/<lesson>.js          STRINGS and run(root, env): the player, loaded only once the step is on screen
    watch/<Name>Watch.tsx      the island for it
    watch/index.ts             the animations by lesson
    watch/WatchAnims.astro     renders the right island (components/lesson/Step.astro)

    python tools/watch_anims.py           # write them
    python tools/watch_anims.py --check   # fail if they are not current (the lesson pages changed)
"""
import glob, json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from slider_labs import NOCHECK, camel, literals, scripts  # noqa: E402
from sort_games import literal  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'web' / 'src' / 'watch'
PLAYER = "const svg = $('fw_svg'); if(!svg) return;"
HEAD = '// Generated by tools/watch_anims.py from %s. Do not edit: change the lesson page, then run the generator again.\n'
USED = {'window.__fwMakeH', 'window.__fwMark', 'window.__fwPaint', 'window.__fwH', 'window.AudioContext', 'window.webkitAudioContext',
        'window.STEM_LANG', 'window.StemSI', 'SCX.addXP', 'SCX.confettiBurst'}


def card(s):
    a = s.index('<div class="lab-card fw-anim">')
    depth = 0
    for m in re.finditer(r'<div\b|</div>', s[a:]):
        depth += 1 if m.group(0) == '<div' else -1
        if depth == 0:
            return s[a:a + m.end()]
    raise ValueError('unclosed card')


def anim(path):
    s = Path(path).read_text(encoding='utf-8')
    sc = scripts(s)
    k = sc.index(PLAYER)
    body = literal(sc, sc.index('{', sc.rindex('(function(){', 0, k)))
    for name in set(re.findall(r'\b((?:window|SCX)\.\w+)', body)):
        if name not in USED:
            sys.exit('%s: the Watch player uses %s; give it to the player in watch/WatchAnim.tsx' % (path, name))
    html = card(s)
    texts = [t.strip() for t in re.findall(r'>([^<>]*[A-Za-z]{2}[^<>]*)<', html)]
    return html, body, [t for t in texts if t] + literals(body)


def render():
    files, index, imports, uses = {}, [], [], []
    for f in sorted(glob.glob(str(ROOT / 'content' / '*' / '*' / '*' / 'lesson.json'))):
        L = json.loads(Path(f).read_text(encoding='utf-8'))
        w = next((st for st in L['steps'] if st['type'] == 'watch'), None)
        if not w:
            continue
        name = w['animation']['file']
        html, body, strings = anim(ROOT / 'site' / 'lessons' / name)
        slug = L['slug']
        src = HEAD % ('site/lessons/' + name)
        files[slug + '.card.js'] = (src + '/** The Watch card as the page has it (in English). */\nexport const HTML = %s;\n') % json.dumps(html, ensure_ascii=False)
        files[slug + '.card.d.ts'] = src + 'export const HTML: string;\n'
        files[slug + '.js'] = (src + '/* eslint-disable */\n' + NOCHECK +
            '/** Its English strings, for the Sinhala looked up at build time. */\n'
            'export const STRINGS = %s;\n\n'
            '/** The page\'s own Watch player (its CFG and the player), run on HTML inside root; env gives it the page\'s helpers. */\n'
            'export function run(root, env) {\n'
            '  const document = { getElementById: (id) => root.querySelector(\'#\' + id), documentElement: globalThis.document.documentElement,\n'
            '    addEventListener: (...a) => globalThis.document.addEventListener(...a) };\n'
            '  const { APP_LANG, window, SCX } = env;\n'
            '  let openerLangHook = null;\n'
            '  (function()%s)();\n'
            '}\n') % (json.dumps(list(dict.fromkeys(strings)), ensure_ascii=False, indent=1), body)
        files[slug + '.d.ts'] = (src + "import type { WatchModule } from './WatchAnim';\n"
            "export const STRINGS: string[];\nexport const run: WatchModule['run'];\n")
        comp = camel(slug) + 'Watch'
        files[comp + '.tsx'] = (src + "import type { SiDict } from '../lib/si-lookup';\n"
            "import WatchAnim from './WatchAnim';\n"
            "import { HTML } from './%s.card.js';\n\n"
            "const load = () => import('./%s.js');\n\n"
            'export default function %s(props: { si?: SiDict; stepId?: string; seg?: [number, number, number] }) {\n'
            '  return <WatchAnim html={HTML} load={load} {...props} />;\n'
            '}\n') % (slug, slug, comp)
        index.append((L['id'], slug))
        imports.append("import %s from './%s';" % (comp, comp))
        uses.append("{island === '%s' && <%s client:visible si={si} stepId={stepId} seg={seg} />}" % (slug, comp))
    files['index.ts'] = ('// Generated by tools/watch_anims.py: the Watch animations by lesson.\n'
        + ''.join("import { STRINGS as S%d } from './%s.js';\n" % (i, s) for i, (_, s) in enumerate(index))
        + '\nexport const WATCH: Record<string, { island: string; strings: string[] }> = {\n'
        + ''.join("  '%s': { island: '%s', strings: S%d },\n" % (lid, s, i) for i, (lid, s) in enumerate(index)) + '};\n')
    files['WatchAnims.astro'] = ('---\n// Generated by tools/watch_anims.py: the island of a Watch animation (components/lesson/Step.astro).\n'
        "import type { SiDict } from '../lib/si-lookup';\n" + '\n'.join(imports) +
        '\ninterface Props { island: string; si: SiDict; stepId: string; seg?: [number, number, number] }\nconst { island, si, stepId, seg } = Astro.props;\n---\n' + '\n'.join(uses) + '\n')
    return files


if __name__ == '__main__':
    files = render()
    keep = {'WatchAnim.tsx'}                         # the hand-written island lives here too
    if '--check' in sys.argv:
        stale = [n for n, t in files.items() if not (OUT / n).is_file() or (OUT / n).read_text(encoding='utf-8').replace('\r\n', '\n') != t]
        extra = [p.name for p in OUT.glob('*') if p.name not in files and p.name not in keep] if OUT.is_dir() else []
        if stale or extra:
            sys.exit('web/src/watch/ is not current (%s): run python tools/watch_anims.py' % ', '.join(stale + extra))
        print('the Watch animations are current (%d files)' % len(files))
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for n, t in files.items():
            (OUT / n).write_text(t, encoding='utf-8', newline='\n')
        print('wrote %d files in %s' % (len(files), OUT.relative_to(ROOT).as_posix()))
