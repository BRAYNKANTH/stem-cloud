# -*- coding: utf-8 -*-
"""Lift the lesson pages' cartoon engine into a module for the new labs: web/src/labs/engine.js (+ engine.d.ts).

Every lesson page has the same engine (window.__fwMakeH in its script: Raja, Chittu, clouds, speech bubbles, arrows,
...), which its lab stage and its Watch animation draw with. It is byte-for-byte the same in all 15 pages, so it is
taken unchanged from one page, checked to be identical in the others, and wrapped as an ES module: makeH(svg, VW, VH,
lang, si). The three names it used from its page are given to it instead: the page language (APP_LANG), the Sinhala
flag (window.STEM_LANG) and the translation helper T(en, ta) (with si(en) for Sinhala). Its colours are read from the stage's
SVG (on the new pages the colour variables are set on the lesson content, not on <html>).

    python tools/lab_engine.py           # write it
    python tools/lab_engine.py --check   # fail if it is not current, or the pages' engines differ
"""
import glob, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'web' / 'src' / 'labs' / 'engine.js'
TYPES = ROOT / 'web' / 'src' / 'labs' / 'engine.d.ts'
START = 'window.__fwMakeH = function(svg, VW, VH){'
END = 'return H;'


def engine(path: str):
    s = Path(path).read_text(encoding='utf-8')
    sc = ''.join(re.findall(r'<script(?![^>]*src)[^>]*>(.*?)</script>', s, re.S))
    a = sc.find(START)
    if a < 0:
        return None
    b = sc.find(END, a)
    return sc[a + len(START):b]


def render():
    found = {}
    for f in sorted(glob.glob(str(ROOT / 'site' / 'lessons' / '*.html'))):
        e = engine(f)
        if e is not None:
            found[Path(f).name] = e
    bodies = set(found.values())
    if len(bodies) != 1:
        sys.exit('the lesson pages have %d different engines; port the differences first' % len(bodies))
    body = bodies.pop()
    # the colours: the old pages set their variables on <html>; the new pages set them on the lesson content (.lc), so
    # the engine reads them where the stage is
    old = "getComputedStyle(document.documentElement)"
    if body.count(old) != 1:
        sys.exit('the engine no longer reads its colours in one place; update tools/lab_engine.py')
    body = body.replace(old, 'getComputedStyle(svg)')
    js = ('// Generated by tools/lab_engine.py from the lesson pages\' cartoon engine (window.__fwMakeH, the same in all %d pages).\n'
          '// Do not edit: change the lesson pages, then run the generator again. The names the engine used from its page\n'
          '// are given to it here: the language (APP_LANG), the Sinhala flag (window.STEM_LANG) and T(en, ta).\n'
          '/* eslint-disable */\n'
          'export function makeH(svg, VW, VH, lang, si) {\n'
          '  const APP_LANG = lang === \'ta\' ? \'ta\' : \'en\';\n'
          '  const window = { STEM_LANG: lang === \'si\' ? \'si\' : \'\', addEventListener: (...a) => globalThis.addEventListener(...a) };\n'
          '  const T = (en, ta) => (lang === \'ta\' ? ta : lang === \'si\' ? (si && si(en)) || en : en);\n'
          '%s\n'
          '  return H;\n'
          '}\n') % (len(found), body.rstrip())
    types = ('// Generated by tools/lab_engine.py. The cartoon engine: draws into an SVG with the stage helpers (H.rect, H.raja, ...).\n'
             'export function makeH(svg: SVGSVGElement, VW: number, VH: number, lang: string, si?: (en: string) => string | null): any;\n')
    return js, types


if __name__ == '__main__':
    js, types = render()
    if '--check' in sys.argv:
        cur = lambda p: p.read_text(encoding='utf-8').replace('\r\n', '\n') if p.is_file() else None
        if cur(OUT) != js or cur(TYPES) != types:
            sys.exit('web/src/labs/engine.js is not current: run python tools/lab_engine.py')
        print('engine.js is current')
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(js, encoding='utf-8', newline='\n')
        TYPES.write_text(types, encoding='utf-8', newline='\n')
        print('wrote %s (%.1f KB)' % (OUT.relative_to(ROOT).as_posix(), len(js.encode()) / 1024))
